import SwiftUI

/// Full-bleed black trackpad tab. The whole background is the tracking surface; two large
/// glass mouse buttons sit on top of it at the bottom of the screen and can be swiped away.
struct TrackpadView: View {
    @ObservedObject var client: NetworkClient

    @AppStorage(TrackpadSettings.sensitivityKey) private var sensitivity = TrackpadSettings.defaultSensitivity
    @AppStorage(TrackpadSettings.tapToClickKey) private var tapToClick = true
    @AppStorage(TrackpadSettings.naturalScrollingKey) private var naturalScrolling = true
    @AppStorage(TrackpadSettings.hapticsKey) private var hapticsEnabled = true

    @State private var controlsVisible = true

    /// Gap between the mouse buttons and the screen edges.
    private let edgeInset: CGFloat = 10
    private let buttonHeight: CGFloat = 100
    /// Space between the two click buttons, twice the edge inset.
    private let buttonGap: CGFloat = 20
    private let innerRadius: CGFloat = 18

    private var configuration: TrackpadGestureEngine.Configuration {
        var configuration = TrackpadGestureEngine.Configuration()
        configuration.sensitivity = sensitivity
        configuration.tapToClick = tapToClick
        configuration.naturalScrolling = naturalScrolling
        return configuration
    }

    var body: some View {
        ZStack(alignment: .bottom) {
            TrackpadSurface(configuration: configuration,
                            hapticsEnabled: hapticsEnabled,
                            onAction: perform)
                .background(Color.black)

            if controlsVisible {
                mouseButtons
                    .transition(.move(edge: .bottom).combined(with: .opacity))
            } else {
                showControlsHandle
                    .transition(.opacity)
            }
        }
        .ignoresSafeArea(edges: .bottom)
        .animation(.snappy, value: controlsVisible)
    }

    // MARK: - Mouse buttons

    /// Left and right click, edge to edge at the bottom. Outer corners are concentric with
    /// the display corners; inner corners are regular.
    private var mouseButtons: some View {
        let outer = DeviceCorners.concentric(inset: edgeInset, minimum: innerRadius)
        return HStack(spacing: buttonGap) {
            MouseButtonView(name: String(localized: "trackpad_left_click"),
                            corners: RectangleCornerRadii(topLeading: innerRadius,
                                                          bottomLeading: outer,
                                                          bottomTrailing: innerRadius,
                                                          topTrailing: innerRadius)) { down in
                client.send(down ? .mouseDown(button: .left) : .mouseUp(button: .left))
            }

            MouseButtonView(name: String(localized: "trackpad_right_click"),
                            corners: RectangleCornerRadii(topLeading: innerRadius,
                                                          bottomLeading: innerRadius,
                                                          bottomTrailing: outer,
                                                          topTrailing: innerRadius)) { down in
                client.send(down ? .mouseDown(button: .right) : .mouseUp(button: .right))
            }
        }
        .glassGroup(spacing: buttonGap)
        .frame(height: buttonHeight)
        .padding(.horizontal, edgeInset)
        .padding(.bottom, edgeInset)
        .highPriorityGesture(
            DragGesture(minimumDistance: 24)
                .onEnded { value in
                    if value.translation.height > 40 {
                        controlsVisible = false
                    }
                }
        )
    }

    private var showControlsHandle: some View {
        Button {
            controlsVisible = true
        } label: {
            Capsule()
                .fill(.white.opacity(0.35))
                .frame(width: 44, height: 5)
                .padding(.horizontal, 24)
                .padding(.vertical, 12)
                .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .padding(.bottom, 8)
        .accessibilityLabel(String(localized: "trackpad_show_controls"))
    }

    // MARK: - Dispatch

    private func perform(_ action: TrackpadAction) {
        switch action {
        case .move(let dx, let dy):
            client.move(dx: dx, dy: dy)
        case .click:
            client.click()
        case .doubleClick:
            client.doubleClick()
        case .rightClick:
            client.click(button: .right)
        case .scroll(let dx, let dy):
            client.scroll(dx: dx, dy: dy)
        case .scrollEnded:
            break // momentum is generated by the surface as plain scroll actions
        case .dragBegan:
            client.send(.mouseDown(button: .left))
        case .dragEnded:
            client.send(.mouseUp(button: .left))
        case .zoom(let steps):
            let code: UInt16 = steps > 0 ? 24 : 27 // "=" and "-" on the US layout, ⌘= zooms in
            for _ in 0..<abs(steps) {
                client.keyPress(code: code, flags: KeyCodes.maskCommand)
            }
        }
    }
}

/// A press-and-hold mouse button: a bare dark glass shape with no label. Sends down on
/// touch and up on release, so the user can hold it while moving with another finger to drag.
struct MouseButtonView: View {
    let name: String
    var corners = RectangleCornerRadii(topLeading: 18, bottomLeading: 18, bottomTrailing: 18, topTrailing: 18)
    let onPress: (_ down: Bool) -> Void

    @State private var isPressed = false

    private var shape: UnevenRoundedRectangle {
        UnevenRoundedRectangle(cornerRadii: corners, style: .continuous)
    }

    var body: some View {
        Color.clear
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .padGlass(in: shape, pressed: isPressed)
            .scaleEffect(isPressed ? 0.97 : 1)
            .animation(.easeOut(duration: 0.08), value: isPressed)
            .contentShape(shape)
            .gesture(
                DragGesture(minimumDistance: 0)
                    .onChanged { _ in
                        guard !isPressed else { return }
                        isPressed = true
                        onPress(true)
                    }
                    .onEnded { _ in
                        guard isPressed else { return }
                        isPressed = false
                        onPress(false)
                    }
            )
            .accessibilityLabel(name)
            .accessibilityAddTraits(.isButton)
    }
}

#Preview("Connected") {
    TrackpadView(client: .preview())
}

#Preview("Not connected") {
    TrackpadView(client: .preview(connected: false))
}

#Preview("Mouse buttons") {
