import SwiftUI

/// Full-bleed black trackpad tab. The whole background is the tracking surface, textured
/// with fine lines that fade out towards the top. The bottom strip, just above the tab bar,
/// is split into left and right click halves by a single separator line.
struct TrackpadView: View {
    @ObservedObject var client: NetworkClient

    @AppStorage(TrackpadSettings.sensitivityKey) private var sensitivity = TrackpadSettings.defaultSensitivity
    @AppStorage(TrackpadSettings.tapToClickKey) private var tapToClick = true
    @AppStorage(TrackpadSettings.twoFingerRightClickKey) private var twoFingerRightClick = true
    @AppStorage(TrackpadSettings.naturalScrollingKey) private var naturalScrolling = true
    @AppStorage(TrackpadSettings.hapticsKey) private var hapticsEnabled = true

    private let buttonHeight: CGFloat = 100

    private var configuration: TrackpadGestureEngine.Configuration {
        var configuration = TrackpadGestureEngine.Configuration()
        configuration.sensitivity = sensitivity
        configuration.tapToClick = tapToClick
        configuration.twoFingerRightClick = twoFingerRightClick
        configuration.naturalScrolling = naturalScrolling
        return configuration
    }

    var body: some View {
        ZStack(alignment: .bottom) {
            TrackpadSurface(configuration: configuration,
                            hapticsEnabled: hapticsEnabled,
                            onAction: perform)
                .background(Color.black)
                .overlay(alignment: .bottom) {
                    SurfaceTexture()
                        .padding(.bottom, buttonHeight)
                }

            mouseButtons
        }
    }

    // MARK: - Mouse buttons

    /// Left and right click halves at the bottom, with only a separator between them.
    private var mouseButtons: some View {
        HStack(spacing: 0) {
            MouseButtonView(name: String(localized: "trackpad_left_click"), haptics: hapticsEnabled) { down in
                client.send(down ? .mouseDown(button: .left) : .mouseUp(button: .left))
            }

            Rectangle()
                .fill(.white.opacity(0.25))
                .frame(width: 1, height: buttonHeight * 0.5)

            MouseButtonView(name: String(localized: "trackpad_right_click"), haptics: hapticsEnabled) { down in
                client.send(down ? .mouseDown(button: .right) : .mouseUp(button: .right))
            }
        }
        .frame(height: buttonHeight)
    }

    // MARK: - Dispatch

    private func perform(_ action: TrackpadAction) {
        switch action {
        case .move(let dx, let dy):
            client.move(dx: dx, dy: dy)
        case .click:
            client.click()
        case .doubleClick:
            client.doubleClick()
        case .rightClick:
            client.click(button: .right)
        case .scroll(let dx, let dy):
            client.scroll(dx: dx, dy: dy)
        case .scrollEnded:
            break // momentum is generated by the surface as plain scroll actions
        case .dragBegan:
            client.send(.mouseDown(button: .left))
        case .dragEnded:
            client.send(.mouseUp(button: .left))
        case .zoom(let steps):
            let code: UInt16 = steps > 0 ? 24 : 27 // "=" and "-" on the US layout, ⌘= zooms in
            for _ in 0..<abs(steps) {
                client.keyPress(code: code, flags: KeyCodes.maskCommand)
            }
        }
    }
}

/// Fine horizontal lines suggesting a physical surface. They start at the bottom of the
/// area and fade to nothing towards the top. Decorative only; never intercepts touches.
struct SurfaceTexture: View {
    var spacing: CGFloat = 14
    var lineOpacity: Double = 0.16

    var body: some View {
        Canvas { context, size in
            var path = Path()
            var y = size.height - spacing / 2
            while y > 0 {
                let py = y.rounded() + 0.5
                path.move(to: CGPoint(x: 0, y: py))
                path.addLine(to: CGPoint(x: size.width, y: py))
                y -= spacing
            }
            context.stroke(path, with: .color(.white.opacity(lineOpacity)), lineWidth: 1)
        }
        .mask(
            LinearGradient(stops: [.init(color: .clear, location: 0),
                                   .init(color: .white, location: 0.85)],
                           startPoint: .top, endPoint: .bottom)
        )
        .allowsHitTesting(false)
    }
}

/// An invisible press-and-hold mouse button: sends down on touch and up on release, so the
/// user can hold it while moving with another finger to drag. Lights up faintly while held
/// and sends a ripple out from the press point.
struct MouseButtonView: View {
    let name: String
    var haptics = true
    let onPress: (_ down: Bool) -> Void

    @State private var isPressed = false
    @State private var ripples: [ClickRipple] = []
    private let impact = UIImpactFeedbackGenerator(style: .light)

    var body: some View {
        Color.white.opacity(isPressed ? 0.08 : 0)
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .animation(.easeOut(duration: 0.08), value: isPressed)
            .overlay {
                ZStack {
                    ForEach(ripples) { ripple in
                        ClickRippleView(ripple: ripple) {
                            ripples.removeAll { $0.id == ripple.id }
                        }
                    }
                }
                .allowsHitTesting(false)
            }
            .clipped()
            .contentShape(Rectangle())
            .gesture(
                DragGesture(minimumDistance: 0)
                    .onChanged { value in
                        guard !isPressed else { return }
                        isPressed = true
                        ripples.append(ClickRipple(location: value.startLocation))
                        if haptics { impact.impactOccurred() }
                        onPress(true)
                    }
                    .onEnded { _ in
                        guard isPressed else { return }
                        isPressed = false
                        if haptics { impact.impactOccurred(intensity: 0.6) }
                        onPress(false)
                    }
            )
            .accessibilityLabel(name)
            .accessibilityAddTraits(.isButton)
    }
}

/// One click ripple at a point.
struct ClickRipple: Identifiable {
    let id = UUID()
    let location: CGPoint
}

/// Ring that grows from the press point and fades, matching the surface's click ripple.
struct ClickRippleView: View {
    let ripple: ClickRipple
    let onFinished: () -> Void

    @State private var expanded = false
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    var body: some View {
        Circle()
            .fill(.white.opacity(0.10))
            .overlay(Circle().stroke(.white.opacity(0.85), lineWidth: expanded ? 1 : 4))
            .frame(width: 72, height: 72)
            .scaleEffect(reduceMotion ? 1 : (expanded ? 1 : 0.3))
            .opacity(expanded ? 0 : 1)
            .position(ripple.location)
            .onAppear {
                withAnimation(.timingCurve(0.2, 0.8, 0.2, 1, duration: 0.55)) {
                    expanded = true
                } completion: {
                    onFinished()
                }
            }
    }
}

