    ZStack(alignment: .bottom) {
        Color.black.ignoresSafeArea()
        HStack(spacing: 0) {
            MouseButtonView(name: "Left") { _ in }
            Rectangle().fill(.white.opacity(0.25)).frame(width: 1, height: 50)
            MouseButtonView(name: "Right") { _ in }
        }
        .frame(height: 100)
    }
}
